-- 在 Python 服务独立的 PostgreSQL 数据库中执行。
BEGIN;

CREATE TABLE IF NOT EXISTS chat_sessions (
    app_id      BIGINT PRIMARY KEY,
    version     BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
    is_deleted  BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS chat_messages (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    app_id       BIGINT NOT NULL REFERENCES chat_sessions (app_id),
    user_id      BIGINT NOT NULL,
    task_id      BIGINT,
    message_type VARCHAR(32) NOT NULL CHECK (message_type IN ('user', 'ai')),
    message      TEXT NOT NULL,
    -- Java 的历史时间是 Asia/Shanghai 本地时间，精度到秒。
    created_at   TIMESTAMP(0) WITHOUT TIME ZONE NOT NULL
                 DEFAULT date_trunc('second', statement_timestamp() AT TIME ZONE 'Asia/Shanghai'),
    updated_at   TIMESTAMP(0) WITHOUT TIME ZONE NOT NULL
                 DEFAULT date_trunc('second', statement_timestamp() AT TIME ZONE 'Asia/Shanghai'),
    is_deleted   BOOLEAN NOT NULL DEFAULT FALSE,
    UNIQUE (app_id, task_id, message_type)
);

CREATE INDEX IF NOT EXISTS idx_chat_messages_app_cursor
    ON chat_messages (app_id, created_at DESC, id DESC) WHERE is_deleted IS FALSE;
CREATE INDEX IF NOT EXISTS idx_chat_messages_created_cursor
    ON chat_messages (created_at DESC, id DESC) WHERE is_deleted IS FALSE;
CREATE INDEX IF NOT EXISTS idx_chat_messages_user_cursor
    ON chat_messages (user_id, created_at DESC, id DESC) WHERE is_deleted IS FALSE;
CREATE INDEX IF NOT EXISTS idx_chat_messages_type_cursor
    ON chat_messages (message_type, created_at DESC, id DESC) WHERE is_deleted IS FALSE;

COMMIT;
